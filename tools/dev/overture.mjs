import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
const server = spawn('node', ['tools/serve.mjs'], { stdio: 'ignore', cwd: '/home/user/Breakbeat' });
await new Promise(r => setTimeout(r, 400));
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required', '--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 2 });
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:4173/');
await page.waitForTimeout(1200);
await page.click('.btn-continue');
await page.waitForTimeout(1200);
await page.screenshot({ path: 'artifacts/o1.png' });
const cell = (c, r) => [167 + 15 + c * 32, 34 + 15 + r * 32];
// wait for a fresh bar then tap target (9,8)
await page.mouse.click(...cell(9, 8));
await page.waitForTimeout(5000);
await page.screenshot({ path: 'artifacts/o2.png' });
const st = await page.evaluate(() => { const a = window.__bb; return { lesson: a.engine && a.run.mode, layers: a.stems.activeLayers, bar: a.engine.currentBar }; });
console.log(JSON.stringify(st), errors.join('\n') || 'no errors');
await browser.close(); server.kill();
