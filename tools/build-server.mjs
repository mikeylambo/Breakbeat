/** Bundles the Supabase edge functions in server/ (game engine included) into build/server/. */

import fs from 'node:fs';
import { build } from 'esbuild';

// Only what the verifier needs from each movement: tempo, colours, rise cadence and quota
const { tracks } = JSON.parse(fs.readFileSync('content/tracks.json', 'utf8'));
fs.mkdirSync('build/server', { recursive: true });
fs.writeFileSync(
  'build/server/track-rules.json',
  JSON.stringify(tracks.filter(t => t.id !== 'overture').map(t => ({ bpm: t.bpm, colors: t.colors, rise: t.riseBars, quota: t.quota })))
);

await build({
  entryPoints: ['server/breakbeat-submit.ts'],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  outfile: 'build/server/breakbeat-submit.js',
  legalComments: 'none',
  minify: true,
  banner: { js: '// Generated by tools/build-server.mjs from server/breakbeat-submit.ts. Do not edit.' }
});
console.log('build/server/breakbeat-submit.js');
