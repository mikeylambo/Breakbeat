/** Bundles the browser game into public/app.js (pixi.js, fonts CSS and content JSON included; no CDN). */
import { build } from 'esbuild';
import fs from 'node:fs';

// index.html: inline the two fonts the boot title needs so it paints with the first frame
const face = (family, weight, file) =>
  `@font-face{font-family:'${family}';font-weight:${weight};font-display:block;src:url(data:font/woff2;base64,${fs.readFileSync(`public/fonts/${file}`).toString('base64')}) format('woff2')}`;
const bootFonts = `<style>${face('Unbounded', 700, 'unbounded-latin-700-normal.woff2')}${face('IBM Plex Mono', 500, 'ibm-plex-mono-latin-500-normal.woff2')}</style>`;
fs.writeFileSync('public/index.html', fs.readFileSync('src/index.html', 'utf8').replace('<!--BOOT_FONTS-->', bootFonts));

await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  format: 'esm',
  target: ['es2022', 'safari15'],
  outfile: 'public/app.js',
  minify: process.env.BB_DEV !== '1',
  // Testing shortcuts (?unlock=…): in local and preview builds only; production strips them as dead code
  define: { __DEV_TOOLS__: JSON.stringify(process.env.VERCEL_ENV !== 'production') },
  sourcemap: true,
  legalComments: 'none',
  loader: { '.json': 'json' },
  logLevel: 'warning'
});
await build({
  entryPoints: ['src/audio/placeholder/synth.worker.ts'],
  bundle: true,
  format: 'iife',
  target: ['es2022', 'safari15'],
  outfile: 'public/synth-worker.js',
  minify: process.env.BB_DEV !== '1',
  logLevel: 'warning'
});
// Service worker: precache every shipped file, versioned by content hash, so the game installs and plays offline
const { createHash } = await import('node:crypto');
const path = await import('node:path');
const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(d => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]));
const files = walk('public')
  .filter(f => !f.endsWith('.map') && !f.endsWith('sw.js') && !f.endsWith('.txt') && !f.includes(`${path.sep}tracks${path.sep}`))
  .map(f => '/' + path.relative('public', f).split(path.sep).join('/'))
  .sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join('public', f)));
const version = hash.digest('hex').slice(0, 12);
const precache = ['/', ...files.filter(f => f !== '/index.html')];
fs.writeFileSync('public/sw.js', `/* BREAKBEAT service worker (generated by tools/bundle.mjs). Cache-first, versioned. */
const CACHE = 'breakbeat-${version}';
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('breakbeat-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then(r => { const copy = r.clone(); caches.open(CACHE).then(c => c.put('/', copy)); return r; }).catch(() => caches.match('/')));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(r => {
    if (r.ok && r.type === 'basic') { const copy = r.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return r;
  })));
});
`);
console.log(`Bundled public/app.js + public/synth-worker.js; sw.js precaches ${precache.length} files (${version})`);
